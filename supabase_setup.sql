-- Run this in Supabase SQL Editor to create the shared public class leaderboard.
create table if not exists public.nstp_lts1_scores (
  id bigint generated by default as identity primary key,
  student_name text not null check (char_length(student_name) between 1 and 40),
  class_section text not null check (char_length(class_section) between 1 and 30),
  score integer not null check (score >= 0 and score <= 460),
  correct integer not null check (correct >= 0 and correct <= 46),
  total integer not null check (total > 0 and total <= 46),
  accuracy integer not null check (accuracy between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.nstp_lts1_scores enable row level security;

drop policy if exists "Anyone can view NSTP scores" on public.nstp_lts1_scores;
create policy "Anyone can view NSTP scores"
on public.nstp_lts1_scores for select
to anon
using (true);

drop policy if exists "Anyone can submit NSTP scores" on public.nstp_lts1_scores;
create policy "Anyone can submit NSTP scores"
on public.nstp_lts1_scores for insert
to anon
with check (
  char_length(student_name) between 1 and 40
  and char_length(class_section) between 1 and 30
  and score >= 0 and score <= 460
  and correct >= 0 and correct <= 46
  and total > 0 and total <= 46
  and accuracy between 0 and 100
);

grant select, insert on public.nstp_lts1_scores to anon;
grant usage, select on sequence public.nstp_lts1_scores_id_seq to anon;
